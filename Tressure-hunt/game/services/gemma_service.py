import json
import os
import re

from dotenv import load_dotenv
from google import genai

load_dotenv()


def generate_game_plan(theme, difficulty, participant_count, objects_per_challenge):
    client = genai.Client(api_key=os.environ["GEMINI_API_KEY"])

    prompt = f"""
    You are an AI game designer for an online team-building game.

    Game configuration:
    - Theme: {theme}
    - Difficulty: {difficulty}
    - Number of players: {participant_count}
    - Hidden objects per challenge: {objects_per_challenge}

    Create exactly {participant_count} unique hidden-object challenges.

    Rules:
    - Every object must be appropriate for the organizer's theme.
    - Objects must be recognizable in a photograph.
    - Avoid abstract concepts.
    - Each challenge must contain exactly {objects_per_challenge} objects.
    - Make the objects suitable for the requested difficulty.
    - Return ONLY valid JSON.

    Required JSON format:
    {{
        "challenges": [
            {{
                "objects": ["stapler"],
                "hint": "Look near the desk."
            }}
        ]
    }}
    """

    response = client.models.generate_content(
        model="gemma-4-26b-a4b-it",
        contents=prompt,
    )

    if not response.text:
        raise ValueError("Gemma returned an empty response.")

    text = response.text.strip()

    # Remove optional Markdown code fences.
    text = re.sub(r"^```(?:json)?\s*", "", text)
    text = re.sub(r"\s*```$", "", text)

    plan = json.loads(text)

    challenges = plan.get("challenges")

    if not isinstance(challenges, list):
        raise ValueError("Invalid challenges format.")

    if len(challenges) != participant_count:
        raise ValueError("Incorrect number of challenges.")

    for challenge in challenges:
        objects = challenge.get("objects")
        hint = challenge.get("hint")

        if (
            not isinstance(objects, list)
            or len(objects) != objects_per_challenge
            or not all(isinstance(obj, str) and obj.strip() for obj in objects)
            or not isinstance(hint, str)
        ):
            raise ValueError("Invalid challenge generated by Gemma.")

    return plan